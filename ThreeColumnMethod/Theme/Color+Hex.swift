import SwiftUI

extension Color {
    /// Builds a Color from a 0xRRGGBB literal, matching how the Android palette is written.
    init(hex: UInt32) {
        let r = Double((hex >> 16) & 0xFF) / 255
        let g = Double((hex >> 8) & 0xFF) / 255
        let b = Double(hex & 0xFF) / 255
        self.init(red: r, green: g, blue: b)
    }
}
